async function runImport() {
  try {
    const uri = process.env.MONGODB_URI;
    if (!uri) {
      console.error('MONGODB_URI is not set!');
      process.exit(1);
    }
    console.log('Connecting to MongoDB...');
    await mongoose.connect(uri);
    console.log('Connected to MongoDB.');

    const lines = rawData.trim().split('\n');
    console.log(`Total lines to parse: ${lines.length}`);

    const operations = [];
    let processedCount = 0;

    for (let line of lines) {
      line = line.trim();
      if (!line || line.startsWith('Account Name')) continue;

      // Split by tab or multiple spaces
      const parts = line.split(/\t+|\s{2,}/);
      let accountName = (parts[0] || '').trim();
      let cityName = (parts[1] || '').trim();

      if (!accountName) continue;

      if (cityName === '..' || cityName === '.' || cityName === '-') {
        cityName = '';
      }
      cityName = cityName.replace(/^["']|["']$/g, '').trim();

      // Format name: if city is valid and not already present in accountName, append " - City"
      let formattedName = accountName;
      if (cityName && !formattedName.toLowerCase().includes(cityName.toLowerCase())) {
        formattedName = `${formattedName} - ${cityName}`;
      }

      operations.push({
        updateOne: {
          filter: { name: formattedName },
          update: { $set: { name: formattedName, city: cityName } },
          upsert: true
        }
      });
      processedCount++;
    }

    console.log(`Parsed ${processedCount} valid customer records.`);
    console.log('Executing bulk upsert to MongoDB...');

    const result = await Customer.bulkWrite(operations);
    console.log(`Bulk write completed! Upserted: ${result.upsertedCount}, Modified: ${result.modifiedCount}, Matched: ${result.matchedCount}`);

    const totalCount = await Customer.countDocuments();
    console.log(`TOTAL CUSTOMERS IN DATABASE NOW: ${totalCount}`);

    process.exit(0);
  } catch (err) {
    console.error('Error importing customers:', err);
    process.exit(1);
  }
}

runImport();
