async function seed() {
  try {
    const uri = process.env.MONGODB_URI;
    if (!uri) {
      console.error('MONGODB_URI is not set in environment!');
      process.exit(1);
    }
    console.log('Connecting to MongoDB...');
    await mongoose.connect(uri);
    console.log('Connected to MongoDB.');

    console.log('Clearing existing customers...');
    await Customer.deleteMany({});

    console.log(`Inserting ${customersData.length} English customers into database...`);
    const inserted = await Customer.insertMany(customersData);
    console.log(`Successfully seeded ${inserted.length} customers in English with 'Name - City' format!`);
    
    process.exit(0);
  } catch (err) {
    console.error('Error seeding customers:', err);
    process.exit(1);
  }
}

