function smartTransliterateWord(word) {
  if (!word) return '';
  const upper = word.toUpperCase();
  if (dictionary[upper]) return dictionary[upper];
  
  // Keep numbers, decimal, fractions, mixed alphanumeric codes intact (e.g., 0.47, 1/10, EBR62229510, DC92-00193)
  if (/^[\d\.\/\*\+\-\,\:\=]+$/.test(word)) return word;
  if (/\d/.test(word)) return word; // token has digits
  
  // Short uppercase acronyms/codes stay as-is unless in dictionary
  if (word === word.toUpperCase() && word.length <= 4) return word;

  return word;
}

/**
 * Converts technical Hinglish product name into clean Gujarati script.
 * Preserves model codes, numbers, and technical acronyms while translating
 * appliance terms, brands, and components into proper Gujarati.
 *
 * @param {string} hinglishText
 * @returns {string} Gujarati text
 */
function hinglishToGujarati(hinglishText) {
  if (!hinglishText || typeof hinglishText !== 'string') return '';

  const trimmed = hinglishText.trim();
  if (!trimmed) return '';

  try {
    const tokens = trimmed.split(/(\s+|[\-\*\/\,\.\+\(\)\:\=])/);
    return tokens.map(token => {
      if (!token || /^\s+$/.test(token) || /^[\-\*\/\,\.\+\(\)\:\=]+$/.test(token)) return token;
      return smartTransliterateWord(token);
    }).join('');
  } catch (err) {
    console.error('Transliteration error:', err.message);
    return trimmed;
  }
}

